/**
 * The decoder playground's entrypoint: /playground.html.
 *
 * A second vite entry rather than a route inside the app, because the two pages
 * have almost nothing in common. This one opens no session and no socket — it
 * never calls `initSession()`, which is the first thing main.ts does — so it
 * runs with the default settings, against no backend, and nothing keyed on it
 * can reach a channel. That is the point: it is a workbench for decoding
 * algorithms, and an experiment that can accidentally transmit is not one.
 *
 * It is not linked to from the app and is not meant to be. It ships in the
 * build because a decoder is tuned against recordings made on real hardware,
 * and the phone or the laptop that produced the awkward hand is not always the
 * one running the dev server.
 */
import { mount } from 'svelte';

import Playground from '$lib/components/playground/Playground.svelte';

// generated by `npm run smui-theme` from src/theme/_smui-theme.scss
import '../theme/smui.css';
import '../theme/base.css';

const target = document.getElementById('root');
if (!target) throw new Error('#root is missing from playground.html');

export default mount(Playground, { target });
